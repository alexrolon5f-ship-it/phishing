CREATE TABLE IF NOT EXISTS sesiones_demo (
 sesion_id CHAR(36) PRIMARY KEY,
 variante VARCHAR(15) NOT NULL CHECK (variante IN ('ia','tradicional')),
 vista SMALLINT NOT NULL DEFAULT 0,
 clic SMALLINT NOT NULL DEFAULT 0,
 intento SMALLINT NOT NULL DEFAULT 0,
 enviado SMALLINT NOT NULL DEFAULT 0,
 opinion VARCHAR(15) CHECK (opinion IN ('ia','tradicional')),
 motivo VARCHAR(500), motivos TEXT, encuesta TEXT,
 fecha TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS eventos_demo (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 sesion_id CHAR(36) NOT NULL,
 evento VARCHAR(15) NOT NULL CHECK (evento IN ('clic','intento')),
 fecha TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE (sesion_id,evento)
);
CREATE TABLE IF NOT EXISTS respuestas (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 mensaje_id VARCHAR(50) NOT NULL,
 clasificacion VARCHAR(15) NOT NULL CHECK (clasificacion IN ('phishing','legitimo')),
 confianza SMALLINT NOT NULL CHECK (confianza BETWEEN 1 AND 5),
 fecha TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS participaciones (
 sesion_id CHAR(36) PRIMARY KEY REFERENCES sesiones_demo(sesion_id),
 nombre VARCHAR(80) NOT NULL,
 apellido VARCHAR(80) NOT NULL,
 consentimiento_version VARCHAR(30) NOT NULL,
 fecha TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
